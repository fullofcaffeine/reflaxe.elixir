    end

    root
  end

  defp apply_options(root, overrides \\ []) do
    lock_content = Keyword.get(overrides, :lock_content, lock_content(%{live_react: git_lock()}))
    revision_reader = Keyword.get(overrides, :git_revision, fn _checkout -> @revision end)

    [
      yes: true,
      mix_dependencies: [],
      git_revision: revision_reader,
      dependency_resolver: fn _context ->
        %{
          lock_content: lock_content,
          dependency_path: Path.join([root, "deps", "live_react"])
        }
      end
    ]
  end

  defp rerun_options do
    [
      yes: true,
      mix_dependencies: [
        {:live_react, [ref: @revision, git: @repository]}
      ],
      git_revision: fn _checkout -> @revision end
    ]
  end

  defp git_lock, do: {:git, @repository, @revision, [ref: @revision]}

  defp lock_content(entries) do
    body =
      entries
      |> Enum.sort_by(fn {name, _entry} -> to_string(name) end)
      |> Enum.map_join(fn {name, entry} -> "  \"#{name}\": #{inspect(entry)},\n" end)

    "%{\n" <> body <> "}\n"
  end

