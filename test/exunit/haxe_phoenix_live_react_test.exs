  defp tree_snapshot(root) do
    root
    |> Path.join("**/*")
    |> Path.wildcard(match_dot: true)
    |> Enum.filter(&File.regular?/1)
    |> Map.new(fn path -> {Path.relative_to(path, root), File.read!(path)} end)
  end

  defp run_live_react_task!(root, arguments) do
    run_external_mix!(root, ["haxe.phoenix.live_react" | arguments])
  end

  defp run_external_mix!(root, arguments) do
    repository_root = Path.expand("../..", __DIR__)
    timeout = Path.join(repository_root, "scripts/with-timeout.sh")

    {output, status} =
      System.cmd(
        timeout,
        ["--secs", "60", "--", "mix" | arguments],
        cd: root,
        env: [{"MIX_ENV", "prod"}],
        stderr_to_stdout: true
      )

    if status != 0 do
      flunk("LiveReact Mix task failed with status #{status}:\n#{output}")
    end

    output
  end

  defp run_node_syntax_check!(root, relative) do
    repository_root = Path.expand("../..", __DIR__)
    timeout = Path.join(repository_root, "scripts/with-timeout.sh")

    {output, status} =
      System.cmd(
        timeout,
        ["--secs", "30", "--", "node", "--check", relative],
        cd: root,
        stderr_to_stdout: true
      )

    if status != 0 do
      flunk("generated JavaScript syntax check failed for #{relative}:\n#{output}")
    end
  end
