    assert result.dependency["sourceKind"] == "path"
    assert result.npm_reference == "file:../vendor/live_react"
    refute File.read!(mix_path) =~ "live_react_dependency"

    HaxePhoenixLiveReact.remove!(root, yes: true)

    assert File.read!(mix_path) =~ ~s({:live_react, path: "vendor/live_react"})
    refute File.exists?(Path.join(root, @manifest))
