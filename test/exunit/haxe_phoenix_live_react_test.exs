defmodule HaxePhoenixLiveReactTest do
  use ExUnit.Case, async: true

  @revision "055e80e6a4e6d009df5e229eb39e7f85f03fea22"
  @repository "https://github.com/mrdotb/live_react.git"
  @manifest "phoenixhx-live-react.json"
  @generated_signature "@generated by mix haxe.phoenix.live_react; do not edit"

  test "Genes project at the root applies, checks, recovers generated files, and removes" do
    root = fixture_root(:genes, ".")
    originals = original_sources(root)

    result = HaxePhoenixLiveReact.apply!(root, apply_options(root))

    assert result.package_root == "."
    assert result.client_mode == :genes
    assert result.npm_reference == "file:deps/live_react"
    assert result.dependency["resolvedRevision"] == @revision

    assert File.read!(Path.join(root, "mix.exs")) =~
             "BEGIN reflaxe_elixir live_react_dependency"

    assert File.read!(Path.join(root, "config/dev.exs")) =~
             ~S|vite: ["npm", "run", "assets:dev", cd: Path.expand("../", __DIR__)]|

    assert File.read!(Path.join(root, "assets/js/app.js")) =~
             "Object.assign(Hooks, reactHooks);"

    assert File.read!(root_layout(root)) =~ """
               <%!-- BEGIN reflaxe_elixir live_react_vite_assets --%>
               <LiveReact.Reload.vite_assets assets={["/js/app.js"]}>
                 <script defer phx-track-static type="text/javascript" src={~p"/assets/app.js"}></script>
               </LiveReact.Reload.vite_assets>
               <%!-- END reflaxe_elixir live_react_vite_assets --%>
           """

    assert :live_react in Map.keys(Mix.Dep.Lock.read(Path.join(root, "mix.lock")))
    assert File.read!(Path.join(root, "vite.config.mjs")) =~ @generated_signature

    manifest = File.read!(Path.join(root, @manifest)) |> Jason.decode!()
    assert manifest["components"] == []

    assert get_in(manifest, ["managed", "restores", "mix.lockOriginalState"]) == %{
             "kind" => "empty",
             "content" => "%{}\n"
           }

    assert HaxePhoenixLiveReact.check!(root, rerun_options())[:mode] == :check

    File.rm!(Path.join([root, "assets", "react-components", "registry.generated.ts"]))
    HaxePhoenixLiveReact.apply!(root, rerun_options())
    assert File.regular?(Path.join([root, "assets", "react-components", "registry.generated.ts"]))

    after_recovery = tree_snapshot(root)
    HaxePhoenixLiveReact.apply!(root, rerun_options())
    assert tree_snapshot(root) == after_recovery

    removed = HaxePhoenixLiveReact.remove!(root, yes: true)

    assert removed.retained_package_keys == []
    refute File.exists?(Path.join(root, @manifest))
    refute File.exists?(Path.join(root, "vite.config.mjs"))
    refute File.exists?(Path.join(root, "assets/js/live-react-hooks.js"))
    refute File.exists?(Path.join([root, "assets", "react-components", "registry.generated.ts"]))
    refute :live_react in Map.keys(Mix.Dep.Lock.read(Path.join(root, "mix.lock")))

    assert File.read!(Path.join(root, "assets/js/app.js")) == originals.app_js
    assert File.read!(root_layout(root)) == originals.root_layout
    assert File.read!(Path.join(root, "config/dev.exs")) == originals.dev_exs
    assert File.read!(Path.join(root, "config/config.exs")) == originals.config_exs
    assert File.read!(Path.join(root, "mix.exs")) == originals.mix_exs
    assert File.read!(Path.join(root, "mix.lock")) == originals.mix_lock

    package = Jason.decode!(File.read!(Path.join(root, "package.json")))
    assert package == %{"name" => "demo-assets"}
  end

