  test "the public Mix task applies, checks, and removes in an external project" do
    root = fixture_root(:plain_js, "assets")
    repository_root = Path.expand("../..", __DIR__)
    File.mkdir_p!(Path.join(root, "vendor"))
    File.cp_r!(Path.join(root, "deps/live_react"), Path.join(root, "vendor/live_react"))

    mix_path = Path.join(root, "mix.exs")

    File.write!(
      mix_path,
      String.replace(
        File.read!(mix_path),
        "defp deps do\n    []",
        """
        defp deps do
            [
              {:jason, path: #{inspect(Path.join(repository_root, "deps/jason"))}, override: true},
              {:reflaxe_elixir, path: #{inspect(repository_root)}},
              {:live_react, path: "vendor/live_react"}
            ]
        """
        |> String.trim_trailing()
      )
    )

    Enum.each(["mix.exs", "config/config.exs", "config/dev.exs"], fn relative ->
      path = Path.join(root, relative)
      formatted = path |> File.read!() |> Code.format_string!() |> IO.iodata_to_binary()
      File.write!(path, formatted <> "\n")
    end)

    run_external_mix!(root, ["deps.get"])
    run_external_mix!(root, ["deps.compile", "reflaxe_elixir"])

    apply_output = run_live_react_task!(root, ["--yes"])
    assert apply_output =~ "PhoenixHx LiveReact integration is current"
    assert apply_output =~ "path:vendor/live_react@0.1.0"

    run_external_mix!(root, [
      "format",
      "--check-formatted",
      "mix.exs",
      "config/config.exs",
      "config/dev.exs"
    ])

    Enum.each(
      [
        "assets/js/app.js",
        "assets/js/live-react-hooks.js",
        "assets/react-components/registry.generated.js",
        "assets/vite.config.mjs"
      ],
      &run_node_syntax_check!(root, &1)
    )

    check_output = run_live_react_task!(root, ["--check"])
    assert check_output =~ "check passed; no writes occurred"

    remove_output = run_live_react_task!(root, ["--remove", "--yes"])
    assert remove_output =~ "Removed all currently owned PhoenixHx LiveReact state"
    refute File.exists?(Path.join(root, @manifest))
    assert File.read!(mix_path) =~ ~s({:live_react, path: "vendor/live_react"})
  end

  defp fixture_root(client_mode, package_root) do
    root =
      Path.join(
        System.tmp_dir!(),
        "reflaxe_live_react_#{client_mode}_#{System.unique_integer([:positive, :monotonic])}"
      )

    on_exit(fn -> File.rm_rf!(root) end)

    write!(root, "mix.exs", mix_exs())
    write!(root, "mix.lock", "%{}\n")
    write!(root, "config/config.exs", "import Config\n\nconfig :demo, ecto_repos: []\n")
    write!(root, "config/dev.exs", dev_exs())
    write!(root, "assets/js/app.js", app_js(client_mode))
    write!(root, "lib/demo_web/components/layouts/root.html.heex", root_layout_source())
    write!(root, Path.join(package_root, "package.json"), ~s({"name":"demo-assets"}\n))
    write!(root, "deps/live_react/package.json", ~s({"name":"live_react","version":"0.1.0"}\n))

    write!(root, "deps/live_react/mix.exs", """
    defmodule LiveReact.MixProject do
      use Mix.Project

      def project, do: [app: :live_react, version: "0.1.0"]
      def application, do: []
    end
    """)

    if client_mode == :genes do
      write!(root, "build-client.hxml", "-lib genes\n")
      write!(root, "src_haxe/client/Boot.hx", "package client; class Boot {}\n")
      write!(root, "haxe_libraries/genes.hxml", "-cp vendor/genes/src\n")
    end

    root
  end

  defp apply_options(root, overrides \\ []) do
    lock_content = Keyword.get(overrides, :lock_content, lock_content(%{live_react: git_lock()}))
    revision_reader = Keyword.get(overrides, :git_revision, fn _checkout -> @revision end)

    [
      yes: true,
      mix_dependencies: [],
      git_revision: revision_reader,
      dependency_resolver: fn _context ->
        %{
          lock_content: lock_content,
          dependency_path: Path.join([root, "deps", "live_react"])
        }
      end
    ]
  end

  defp rerun_options do
    [
      yes: true,
      mix_dependencies: [
        {:live_react, [ref: @revision, git: @repository]}
      ],
      git_revision: fn _checkout -> @revision end
    ]
  end

  defp git_lock, do: {:git, @repository, @revision, [ref: @revision]}

  defp lock_content(entries) do
    body =
      entries
      |> Enum.sort_by(fn {name, _entry} -> to_string(name) end)
      |> Enum.map_join(fn {name, entry} -> "  \"#{name}\": #{inspect(entry)},\n" end)

    "%{\n" <> body <> "}\n"
  end

  defp mix_exs do
    """
    defmodule Demo.MixProject do
      use Mix.Project

      def project do
        [app: :demo, version: "0.1.0", deps: deps(), aliases: aliases()]
      end

      def application, do: [extra_applications: [:logger]]

      defp deps do
        []
      end

      defp aliases do
        [
          "assets.setup": ["esbuild.install --if-missing"],
          "assets.build": ["esbuild demo"],
          "assets.deploy": ["esbuild demo --minify", "phx.digest"]
        ]
      end
    end
    """
  end

  defp dev_exs do
    """
    import Config

    config :demo, DemoWeb.Endpoint,
      http: [ip: {127, 0, 0, 1}, port: 4000],
      watchers: [
        esbuild: {Esbuild, :install_and_run, [:demo, ~w(--sourcemap=inline --watch)]},
        tailwind: {Tailwind, :install_and_run, [:demo, ~w(--watch)]}
      ]
    """
  end

  defp app_js(:genes) do
    """
    import "phoenix_html"
    import {Socket} from "phoenix"
    import {LiveSocket} from "phoenix_live_view"

    let Hooks = {};
    const liveSocket = new LiveSocket("/live", Socket, {hooks: Hooks})
    liveSocket.connect()
    """
  end

  defp app_js(:plain_js) do
    """
    import "phoenix_html"
    import {Socket} from "phoenix"
    import {LiveSocket} from "phoenix_live_view"
    import {hooks as colocatedHooks} from "phoenix-colocated/demo"

    const liveSocket = new LiveSocket("/live", Socket, {
      params: {_csrf_token: "test"},
      hooks: {...colocatedHooks},
    })

    liveSocket.connect()
    """
  end

  defp root_layout_source do
    """
    <!DOCTYPE html>
    <html lang="en">
      <head>
        <meta charset="utf-8" />
        <script defer phx-track-static type="text/javascript" src={~p"/assets/app.js"}></script>
      </head>
      <body>{@inner_content}</body>
    </html>
    """
  end

  defp root_layout(root),
    do: Path.join(root, "lib/demo_web/components/layouts/root.html.heex")

  defp original_sources(root) do
    %{
      app_js: File.read!(Path.join(root, "assets/js/app.js")),
      config_exs: File.read!(Path.join(root, "config/config.exs")),
      dev_exs: File.read!(Path.join(root, "config/dev.exs")),
      mix_exs: File.read!(Path.join(root, "mix.exs")),
      mix_lock: File.read!(Path.join(root, "mix.lock")),
      root_layout: File.read!(root_layout(root))
    }
  end

  defp write!(root, relative, content) do
    path = Path.join(root, relative)
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, content)
  end

  defp tree_snapshot(root) do
    root
    |> Path.join("**/*")
    |> Path.wildcard(match_dot: true)
    |> Enum.filter(&File.regular?/1)
    |> Map.new(fn path -> {Path.relative_to(path, root), File.read!(path)} end)
  end

  defp run_live_react_task!(root, arguments) do
    run_external_mix!(root, ["haxe.phoenix.live_react" | arguments])
  end

  defp run_external_mix!(root, arguments) do
    repository_root = Path.expand("../..", __DIR__)
    timeout = Path.join(repository_root, "scripts/with-timeout.sh")

    {output, status} =
      System.cmd(
        timeout,
        ["--secs", "60", "--", "mix" | arguments],
        cd: root,
        env: [{"MIX_ENV", "prod"}],
        stderr_to_stdout: true
      )

    if status != 0 do
      flunk("LiveReact Mix task failed with status #{status}:\n#{output}")
    end

    output
  end

  defp run_node_syntax_check!(root, relative) do
    repository_root = Path.expand("../..", __DIR__)
    timeout = Path.join(repository_root, "scripts/with-timeout.sh")

    {output, status} =
      System.cmd(
        timeout,
        ["--secs", "30", "--", "node", "--check", relative],
        cd: root,
        stderr_to_stdout: true
      )

    if status != 0 do
      flunk("generated JavaScript syntax check failed for #{relative}:\n#{output}")
    end
  end
end

defmodule Mix.Tasks.Haxe.Phoenix.LiveReactTest do
  use ExUnit.Case, async: false

  test "SSR and conflicting modes are rejected before project discovery" do
    assert_raise RuntimeError, ~r/--ssr is not supported/, fn ->
      Mix.Tasks.Haxe.Phoenix.LiveReact.run(["--ssr"])
    end

    assert_raise RuntimeError, ~r/mutually exclusive/, fn ->
      Mix.Tasks.Haxe.Phoenix.LiveReact.run(["--check", "--remove"])
    end
  end
end
