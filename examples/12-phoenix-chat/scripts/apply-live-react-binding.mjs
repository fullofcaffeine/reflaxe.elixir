import fs from "node:fs"
import path from "node:path"
import process from "node:process"
import {fileURLToPath} from "node:url"

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(scriptDirectory, "..")
const checkOnly = process.argv.includes("--check")
const manifestPath = path.join(projectRoot, "live-react-binding.json")
const generatedSignature = "@generated by scripts/apply-live-react-binding.mjs; do not edit"
const changes = []

function fail(message) {
  throw new Error(`[live-react binding] ${message}`)
}

function read(relativePath) {
  return fs.readFileSync(path.join(projectRoot, relativePath), "utf8")
}

function exactKeys(value, expected, label) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    fail(`${label} must be an object`)
  }
  const actual = Object.keys(value).sort()
  const wanted = [...expected].sort()
  if (JSON.stringify(actual) !== JSON.stringify(wanted)) {
    fail(`${label} keys must be exactly ${wanted.join(", ")}; received ${actual.join(", ")}`)
  }
}

function exactArray(value, expected, label) {
  if (!Array.isArray(value) || JSON.stringify(value) !== JSON.stringify(expected)) {
    fail(`${label} must be exactly ${JSON.stringify(expected)}`)
  }
}

function validateManifest(manifest) {
  exactKeys(manifest, ["schema", "bindingId", "assetMode", "sourcePins", "runtimePolicy", "components"], "manifest")
  if (manifest.schema !== "phoenix-chat.live-react-binding@1") fail("unsupported manifest schema")
  if (manifest.bindingId !== "phoenix-chat-vite-live-react") fail("unexpected binding ID")
  if (manifest.assetMode !== "vite-live-react") fail("Vite must be the only JavaScript asset mode")

  exactKeys(manifest.sourcePins, ["phoenixHxBaseline", "liveReact"], "sourcePins")
  for (const [name, pin] of Object.entries(manifest.sourcePins)) {
    exactKeys(pin, ["repository", "revision"], `sourcePins.${name}`)
    if (!/^[0-9a-f]{40}$/.test(pin.revision)) fail(`sourcePins.${name}.revision must be a full Git SHA`)
  }
  if (manifest.sourcePins.phoenixHxBaseline.repository !== "https://github.com/fullofcaffeine/reflaxe.elixir") {
    fail("PhoenixHx must remain pinned to the project-owned upstream repository")
  }
  if (manifest.sourcePins.liveReact.repository !== "https://github.com/mrdotb/live_react") {
    fail("live_react must remain the stock upstream repository")
  }

  exactKeys(
    manifest.runtimePolicy,
    ["trustedFirstPartyOnly", "ssr", "slots", "uploads", "streams", "maxPublicInputBytes", "maxEventPayloadBytes"],
    "runtimePolicy",
  )
  if (manifest.runtimePolicy.trustedFirstPartyOnly !== true) fail("the first proof is trusted-first-party only")
  for (const feature of ["ssr", "slots", "uploads", "streams"]) {
    if (manifest.runtimePolicy[feature] !== false) fail(`${feature} must stay disabled in the first proof`)
  }
  if (manifest.runtimePolicy.maxPublicInputBytes !== 512) fail("public input budget must remain 512 bytes")
  if (manifest.runtimePolicy.maxEventPayloadBytes !== 64) fail("event payload budget must remain 64 bytes")

  if (!Array.isArray(manifest.components) || manifest.components.length !== 1) {
    fail("the first proof must expose exactly one component")
  }
  const component = manifest.components[0]
  exactKeys(component, ["name", "module", "export", "publicInputs", "densityValues", "event"], "components[0]")
  if (component.name !== "PreferenceStudio") fail("unexpected component name")
  if (component.module !== "./preference-studio-boundary") fail("unexpected component module")
  if (component.export !== "PreferenceStudioBoundary") fail("unexpected component export")
  exactArray(component.publicInputs, ["title", "density"], "components[0].publicInputs")
  exactArray(component.densityValues, ["calm", "focused", "dense"], "components[0].densityValues")
  exactKeys(component.event, ["name", "payloadFields"], "components[0].event")
  if (component.event.name !== "preference_changed") fail("unexpected event name")
  exactArray(component.event.payloadFields, ["density"], "components[0].event.payloadFields")
}

function record(relativePath, current, expected) {
  if (current === expected) return
  if (checkOnly) {
    changes.push(relativePath)
    return
  }
  fs.mkdirSync(path.dirname(path.join(projectRoot, relativePath)), {recursive: true})
  fs.writeFileSync(path.join(projectRoot, relativePath), expected)
  changes.push(relativePath)
}

function generatedFile(relativePath, expected) {
  const absolutePath = path.join(projectRoot, relativePath)
  const current = fs.existsSync(absolutePath) ? fs.readFileSync(absolutePath, "utf8") : ""
  if (current !== "" && !current.includes(generatedSignature)) {
    fail(`${relativePath} exists without the generated ownership signature`)
  }
  record(relativePath, current, expected)
}

function replaceMarker(relativePath, begin, end, body) {
  const current = read(relativePath)
  const beginCount = current.split(begin).length - 1
  const endCount = current.split(end).length - 1
  if (beginCount !== 1 || endCount !== 1) {
    fail(`${relativePath} must contain exactly one ${begin} / ${end} marker pair`)
  }
  const start = current.indexOf(begin)
  const finish = current.indexOf(end, start)
  if (finish < start) fail(`${relativePath} has an inverted marker pair`)
  const expectedBlock = `${begin}\n${body}\n${end}`
  const next = current.slice(0, start) + expectedBlock + current.slice(finish + end.length)
  record(relativePath, current, next)
}

function ensureAbsent(relativePath, snippets) {
  const source = read(relativePath)
  for (const snippet of snippets) {
    if (source.includes(snippet)) fail(`${relativePath} still contains forbidden JavaScript bundler surface: ${snippet}`)
  }
}

function mergePackageJson(manifest) {
  const relativePath = "package.json"
  const current = read(relativePath)
  const value = JSON.parse(current)
  value.private = true
  value.type = "module"
  value.scripts = value.scripts ?? {}
  value.devDependencies = value.devDependencies ?? {}
  value.dependencies = value.dependencies ?? {}

  const scripts = {
    "assets:dev": "vite --host 127.0.0.1 --port 5173 --strictPort --logLevel warn",
    "assets:build": "vite build",
    "bind:live-react": "node scripts/apply-live-react-binding.mjs",
    "bind:live-react:check": "node scripts/apply-live-react-binding.mjs --check",
    "typecheck": "tsc --noEmit",
    "test:frontend": "vitest run",
    "test:binding": "node --test test/live-react-binding.test.mjs"
  }
  const devDependencies = {
    "@testing-library/react": "16.3.0",
    "@testing-library/user-event": "14.6.1",
    "@types/node": "22.15.32",
    "@types/react": "19.1.8",
    "@types/react-dom": "19.1.6",
    "@vitejs/plugin-react": "4.5.2",
    "jsdom": "26.1.0",
    "typescript": "5.8.3",
    "vite": "7.2.7",
    "vitest": "3.2.4"
  }
  const dependencies = {
    "live_react": `https://github.com/mrdotb/live_react/archive/${manifest.sourcePins.liveReact.revision}.tar.gz`,
    "phoenix": "1.7.24",
    "phoenix_html": "4.3.0",
    "phoenix_live_view": "0.20.17",
    "react": "19.1.0",
    "react-dom": "19.1.0",
    "topbar": "2.0.0"
  }

  mergeManaged(value.scripts, scripts, "scripts")
  mergeManaged(value.devDependencies, devDependencies, "devDependencies")
  mergeManaged(value.dependencies, dependencies, "dependencies")
  record(relativePath, current, `${JSON.stringify(value, null, 2)}\n`)
}

function mergeManaged(target, expected, label) {
  for (const [key, value] of Object.entries(expected)) {
    if (Object.hasOwn(target, key) && target[key] !== value) {
      fail(`package.json ${label}.${key} conflicts with the managed value`)
    }
    target[key] = value
  }
}

function renderGeneratedContract(manifest) {
  const component = manifest.components[0]
  return `/* ${generatedSignature} */
export const LIVE_REACT_SOURCE_REVISION = ${JSON.stringify(manifest.sourcePins.liveReact.revision)} as const
export const PREFERENCE_DENSITIES = ${JSON.stringify(component.densityValues)} as const
export const PREFERENCE_CHANGED_EVENT = ${JSON.stringify(component.event.name)} as const
export const MAX_PUBLIC_INPUT_BYTES = ${manifest.runtimePolicy.maxPublicInputBytes} as const
export const MAX_EVENT_PAYLOAD_BYTES = ${manifest.runtimePolicy.maxEventPayloadBytes} as const
`
}

function renderGeneratedRegistry(manifest) {
  const component = manifest.components[0]
  return `/* ${generatedSignature} */
import {${component.export}} from ${JSON.stringify(component.module)}

export const componentRegistry = {
  ${component.name}: ${component.export},
} as const

export type ComponentName = keyof typeof componentRegistry

export default componentRegistry
`
}

try {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"))
  validateManifest(manifest)

  const liveReactRevision = manifest.sourcePins.liveReact.revision
  replaceMarker(
    "mix.exs",
    "      # BEGIN phoenix_chat vite_live_react_dependency",
    "      # END phoenix_chat vite_live_react_dependency",
    `      {:live_react,\n       git: "https://github.com/mrdotb/live_react.git",\n       ref: "${liveReactRevision}"},`,
  )
  replaceMarker(
    "mix.exs",
    "      # BEGIN phoenix_chat vite_live_react_assets_setup",
    "      # END phoenix_chat vite_live_react_assets_setup",
    '      "assets.setup": ["cmd npm ci --no-audit --no-fund", "tailwind.install --if-missing"],',
  )
  replaceMarker(
    "mix.exs",
    "      # BEGIN phoenix_chat vite_live_react_assets_build",
    "      # END phoenix_chat vite_live_react_assets_build",
    '      "assets.build": [\n        "haxe.compile.client",\n        "cmd npm run typecheck",\n        "cmd npm run assets:build",\n        "tailwind phoenix_chat"\n      ],',
  )
  replaceMarker(
    "mix.exs",
    "      # BEGIN phoenix_chat vite_live_react_assets_deploy",
    "      # END phoenix_chat vite_live_react_assets_deploy",
    '      "assets.deploy": [\n        "haxe.compile.client",\n        "cmd npm run typecheck",\n        "cmd npm run assets:build",\n        "tailwind phoenix_chat --minify",\n        "phx.digest"\n      ],',
  )
  replaceMarker(
    "config/config.exs",
    "# BEGIN phoenix_chat vite_live_react_config",
    "# END phoenix_chat vite_live_react_config",
    "# The first proof is client-only: stock live_react never starts an SSR runtime.\nconfig :live_react, ssr: false",
  )
  replaceMarker(
    "config/dev.exs",
    "         # BEGIN phoenix_chat vite_live_react_watcher",
    "         # END phoenix_chat vite_live_react_watcher",
    '         vite: ["npm", "run", "assets:dev", cd: Path.expand("../", __DIR__)],',
  )
  replaceMarker(
    "config/dev.exs",
    "# BEGIN phoenix_chat vite_live_react_host",
    "# END phoenix_chat vite_live_react_host",
    'config :live_react,\n  vite_host: if(disable_watchers, do: nil, else: "http://127.0.0.1:5173"),\n  ssr: false\n',
  )
  replaceMarker(
    "lib/phoenix_chat_web.ex",
    "      # BEGIN phoenix_chat vite_live_react_imports",
    "      # END phoenix_chat vite_live_react_imports",
    "      import LiveReact\n      import PhoenixChatWeb.ReactComponents",
  )
  replaceMarker(
    "lib/phoenix_chat_web/components/layouts/root.html.heex",
    "    <%!-- BEGIN phoenix_chat vite_live_react_assets --%>",
    "    <%!-- END phoenix_chat vite_live_react_assets --%>",
    '    <LiveReact.Reload.vite_assets assets={["/js/app.js"]}>\n      <script defer phx-track-static type="text/javascript" src={~p"/assets/app.js"}>\n      </script>\n    </LiveReact.Reload.vite_assets>',
  )
  replaceMarker(
    "assets/js/app.js",
    "// BEGIN phoenix_chat vite_topbar_import",
    "// END phoenix_chat vite_topbar_import",
    'import topbar from "topbar"',
  )
  replaceMarker(
    "assets/js/app.js",
    "// BEGIN phoenix_chat vite_live_react_imports",
    "// END phoenix_chat vite_live_react_imports",
    'import {reactHooks} from "./live-react-hooks"',
  )
  replaceMarker(
    "assets/js/app.js",
    "  // BEGIN phoenix_chat vite_live_react_hooks",
    "  // END phoenix_chat vite_live_react_hooks",
    "  hooks: {...(window.Hooks || {}), ...reactHooks},",
  )
  replaceMarker(
    "assets/tailwind.config.js",
    "    // BEGIN phoenix_chat vite_live_react_content",
    "    // END phoenix_chat vite_live_react_content",
    '    "./react-components/**/*.{ts,tsx}",',
  )

  ensureAbsent("mix.exs", ["{:esbuild,"])
  ensureAbsent("config/config.exs", ["config :esbuild"])
  ensureAbsent("config/dev.exs", ["esbuild:"])
  mergePackageJson(manifest)
  generatedFile("assets/react-components/binding-contract.generated.ts", renderGeneratedContract(manifest))
  generatedFile("assets/react-components/registry.generated.ts", renderGeneratedRegistry(manifest))

  if (changes.length > 0 && checkOnly) {
    fail(`managed files are stale: ${changes.join(", ")}`)
  }
  if (changes.length > 0) {
    process.stdout.write(`[live-react binding] updated ${changes.join(", ")}\n`)
  } else {
    process.stdout.write("[live-react binding] already current\n")
  }
} catch (error) {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 1
}
