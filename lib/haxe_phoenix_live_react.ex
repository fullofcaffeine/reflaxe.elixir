  defp patch_single_line_asset_alias!(
         lines,
         index,
         alias_name,
         desired_line,
         begin_token,
         end_token,
         restore_key,
         restores
       ) do
    original = Enum.at(lines, index)

    if find_unowned_vite_task(lines, index, index) do
      raise "mix.exs #{alias_name} already contains an unowned Vite task. No writes occurred. Adopt the exact PhoenixHx marker block or use manual integration."
    end

    desired = render_single_line_asset_alias!(original, alias_name, desired_line)
    indent = leading_indent(original)
    block = marker_lines(begin_token, end_token, desired, indent, "#")
    updated = lines |> List.replace_at(index, Enum.join(block, "\n")) |> Enum.join("\n")
    {updated, put_restore!(restores, restore_key, original)}
  end

  defp patch_multiline_asset_alias!(
         lines,
         start_index,
         end_index,
         alias_name,
         desired,
         begin_token,
         end_token,
         restore_key,
         restores
       ) do
    esbuild_indices =
      start_index..end_index
      |> Enum.filter(fn index ->
        line = Enum.at(lines, index)
        Regex.match?(~r/^\s*\"?esbuild(?:\.install|\s)/, String.trim_leading(line))
      end)

    cond do
      length(esbuild_indices) > 1 ->
        raise "mix.exs #{alias_name} contains multiple esbuild tasks. No writes occurred. Manual integration is required."

      length(esbuild_indices) == 1 ->
        index = hd(esbuild_indices)
        original = Enum.at(lines, index)
        indent = leading_indent(original)
        restores = put_restore!(restores, restore_key, original)
        block = marker_lines(begin_token, end_token, desired, indent, "#")
        {lines |> List.replace_at(index, Enum.join(block, "\n")) |> Enum.join("\n"), restores}

      find_unowned_vite_task(lines, start_index, end_index) ->
        raise "mix.exs #{alias_name} already contains an unowned Vite task. No writes occurred. Adopt the exact PhoenixHx marker block or use manual integration."

      true ->
        insert_at = alias_insertion_index(lines, start_index, end_index)
        indent = alias_entry_indent(lines, start_index, end_index)
        block = marker_lines(begin_token, end_token, desired, indent, "#")
        updated = List.insert_at(lines, insert_at, Enum.join(block, "\n")) |> Enum.join("\n")
        {updated, put_restore!(restores, restore_key, nil)}
    end
  end

  defp desired_asset_alias_lines(alias_name, desired_line, original)
       when is_binary(original) do
    if single_line_alias?(original, alias_name),
      do: render_single_line_asset_alias!(original, alias_name, desired_line),
      else: [desired_line]
