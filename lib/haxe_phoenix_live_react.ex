  defp plan_package_json!(topology, dependency, existing_manifest) do
    content = File.read!(topology.package_json)

    value =
      case Jason.decode(content) do
        {:ok, map} when is_map(map) ->
          map

        {:ok, _other} ->
          raise "#{topology.package_json} must contain a JSON object. No writes occurred."

        {:error, error} ->
          raise "cannot parse #{topology.package_json}: #{Exception.message(error)}"
      end

    existing_owned =
      case existing_manifest do
        nil -> MapSet.new()
        manifest -> MapSet.new(manifest["managed"]["packageKeys"])
      end

    {updated, owned_keys} =
      Enum.reduce(@managed_package_values, {value, existing_owned}, fn {path, raw_expected},
                                                                       {json, owned} ->
        expected =
          if raw_expected == :npm_live_react_reference,
            do: dependency.npm_reference,
            else: raw_expected

        dotted = Enum.join(path, ".")

        case fetch_json_path(json, path) do
          :missing ->
            {put_json_path(json, path, expected), MapSet.put(owned, dotted)}

          {:ok, ^expected} ->
            {json, owned}

          {:ok, actual} ->
            raise "#{topology.package_json} #{dotted} conflicts with the managed value. Found #{inspect(actual)}, expected #{inspect(expected)}. No writes occurred. Preserve the existing value and use manual integration, or remove it before retrying."
        end
      end)

    %{
      content: Jason.encode!(updated, pretty: true) <> "\n",
      owned_keys: owned_keys |> MapSet.to_list() |> Enum.sort()
    }
  end

  defp fetch_json_path(json, [key]) when is_map(json) do
    if Map.has_key?(json, key), do: {:ok, Map.fetch!(json, key)}, else: :missing
  end

  defp fetch_json_path(json, [key | rest]) when is_map(json) do
    case Map.fetch(json, key) do
      {:ok, child} when is_map(child) ->
        fetch_json_path(child, rest)

      {:ok, child} ->
        raise "package.json #{key} must be an object, found #{inspect(child)}. No writes occurred."

      :error ->
        :missing
    end
  end

  defp put_json_path(json, [key], value) when is_map(json), do: Map.put(json, key, value)

  defp put_json_path(json, [key | rest], value) when is_map(json) do
    child = Map.get(json, key, %{})

    unless is_map(child) do
      raise "package.json #{key} must be an object, found #{inspect(child)}. No writes occurred."
    end

    Map.put(json, key, put_json_path(child, rest, value))
  end

  defp delete_json_path(json, [key]) when is_map(json), do: Map.delete(json, key)

  defp delete_json_path(json, [key | rest]) when is_map(json) do
    case Map.fetch(json, key) do
      {:ok, child} when is_map(child) ->
        updated = delete_json_path(child, rest)

        if map_size(updated) == 0,
          do: Map.delete(json, key),
          else: Map.put(json, key, updated)

      _ ->
        json
    end
  end

