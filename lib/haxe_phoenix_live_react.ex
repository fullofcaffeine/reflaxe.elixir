  @type mode :: :apply | :check | :remove
  @type option ::
          {:package_root, binary() | nil}
          | {:client_mode, :genes | :plain_js | nil}
          | {:mix_dependencies, list()}
          | {:dependency_resolver, (map() -> map())}
          | {:git_revision, (Path.t() -> binary())}
          | {:yes, boolean()}
          | {:confirm, (binary() -> boolean())}
          | {:report, (binary() -> any())}
          | {:warn_only, boolean()}

  @spec apply!(Path.t(), [option()]) :: map() | :cancelled
  def apply!(project_root, opts \\ []), do: execute!(project_root, :apply, opts)

  @spec check!(Path.t(), [option()]) :: map()
  def check!(project_root, opts \\ []), do: execute!(project_root, :check, opts)

  @spec remove!(Path.t(), [option()]) :: map() | :cancelled
  def remove!(project_root, opts \\ []), do: execute!(project_root, :remove, opts)

  @spec execute!(Path.t(), mode(), [option()]) :: map() | :cancelled
  def execute!(project_root, mode, opts \\ [])
      when is_binary(project_root) and mode in [:apply, :check, :remove] and is_list(opts) do
    root = canonical_project_root!(project_root)
    recovery_status = ProjectPatch.recovery_status!(root)

    if mode == :check and recovery_status != :clean do
      raise "LiveReact integration check found an interrupted project patch transaction (#{inspect(recovery_status)}). No writes occurred. Re-run `mix haxe.phoenix.live_react` to recover it, then run `--check` again."
    end

    if mode != :check do
      ProjectPatch.recover!(root)
    end

    existing_manifest = read_manifest(root, mode)

    result =
      case mode do
        :remove -> build_remove_plan!(root, existing_manifest, opts)
        :apply -> build_apply_plan!(root, existing_manifest, opts, true)
        :check -> build_apply_plan!(root, existing_manifest, opts, false)
      end

    finish_execution!(result, mode, opts)
  end

  @doc false
  def default_live_react_dependency do
    {:live_react, git: @live_react_repository, ref: @live_react_revision}
  end

  @doc false
  def compatibility do
    %{
      repository: @live_react_repository,
      revision: @live_react_revision,
      react: "19.1.0",
      react_dom: "19.1.0",
      vite: "7.2.7"
    }
  end

  defp finish_execution!(%{plan: plan} = result, :check, _opts) do
    case ProjectPatch.changes(plan) do
      [] -> Map.drop(result, [:plan])
      changes -> raise_drift!(changes)
    end
  end

  defp finish_execution!(%{plan: plan} = result, mode, opts) when mode in [:apply, :remove] do
    changes = ProjectPatch.changes(plan)
    report = Keyword.get(opts, :report, &IO.puts/1)

    Enum.each(changes, fn change ->
      report.("[live-react] #{change.action} #{change.relative}")
    end)

    cond do
      changes == [] ->
        Map.drop(result, [:plan])

      Keyword.get(opts, :yes, false) ->
        ProjectPatch.publish!(plan)
        Map.drop(result, [:plan])

      true ->
        confirm = Keyword.get(opts, :confirm, fn _prompt -> false end)

        if confirm.(confirmation_prompt(mode, length(changes))) do
          ProjectPatch.publish!(plan)
          Map.drop(result, [:plan])
        else
          :cancelled
        end
    end
  end

  defp confirmation_prompt(:apply, count),
    do: "Apply #{count} owned PhoenixHx LiveReact project change(s)?"

  defp confirmation_prompt(:remove, count),
    do: "Remove #{count} owned PhoenixHx LiveReact project change(s)?"

  defp raise_drift!(changes) do
    paths = Enum.map_join(changes, "\n", &"  - #{&1.relative}")

    raise "LiveReact integration drift detected:\n#{paths}\nNo writes occurred. Run `mix haxe.phoenix.live_react` to reconcile owned state, or `--remove` to remove it."
  end

  defp canonical_project_root!(project_root) do
    expanded = Path.expand(project_root)

    case physical_directory(expanded) do
      {:ok, real} ->
        require_regular_file!(Path.join(real, "mix.exs"), "Mix project")
        real

      {:error, reason} ->
        raise "cannot resolve Phoenix project root #{expanded}: #{format_path_error(reason)}"
    end
  end

  defp require_regular_file!(path, label) do
    case File.lstat(path) do
      {:ok, %{type: :regular}} -> :ok
      {:ok, stat} -> raise "expected #{label} file at #{path}, found #{inspect(stat.type)}"
      {:error, reason} -> raise "expected #{label} file at #{path}: #{:file.format_error(reason)}"
    end
  end

  defp read_manifest(root, mode) do
    path = Path.join(root, @manifest_filename)

    case File.read(path) do
      {:ok, content} ->
        validate_manifest!(Jason.decode!(content), path)

      {:error, :enoent} when mode == :remove ->
        raise "cannot remove PhoenixHx LiveReact integration: #{@manifest_filename} is missing. No writes occurred. Restore the owned manifest or remove the integration manually after reviewing every marker."

      {:error, :enoent} when mode == :check ->
        raise "LiveReact integration drift detected: #{@manifest_filename} is missing. No writes occurred. Run `mix haxe.phoenix.live_react` to install it."

      {:error, :enoent} ->
        nil

      {:error, reason} ->
        raise "cannot read #{path}: #{:file.format_error(reason)}"
    end
  rescue
    error in Jason.DecodeError ->
      raise "invalid #{@manifest_filename}: #{Exception.message(error)}. No writes occurred."
  end

  defp validate_manifest!(manifest, path) when is_map(manifest) do
    unless manifest["schema"] == @schema and manifest["generatedBy"] == @generated_by do
      raise "unsupported or unowned LiveReact integration manifest at #{path}. No writes occurred."
    end

    required = [
      "schema",
      "generatedBy",
      "assetMode",
      "packageRoot",
      "clientMode",
      "mixDependency",
      "npmReference",
      "runtimePolicy",
      "components",
      "managed"
    ]

    unless Enum.sort(Map.keys(manifest)) == Enum.sort(required) do
      raise "#{path} has an unsupported key set. No writes occurred. Upgrade the integration tool or restore its generated manifest."
    end

    managed = manifest["managed"]

    unless is_map(managed) and is_list(managed["files"]) and is_list(managed["markers"]) and
             is_list(managed["packageKeys"]) and is_map(managed["restores"]) and
             is_boolean(managed["dependencyOwned"]) and is_boolean(managed["lockOwned"]) do
      raise "#{path} has invalid managed ownership metadata. No writes occurred."
    end

    unless manifest["assetMode"] == "vite" and
             manifest["clientMode"] in ["genes", "plain-js"] and
             is_binary(manifest["packageRoot"]) and is_map(manifest["mixDependency"]) and
             is_binary(manifest["npmReference"]) and is_map(manifest["runtimePolicy"]) and
             is_list(manifest["components"]) do
      raise "#{path} has invalid integration metadata. No writes occurred."
    end

    manifest
  end

  defp validate_manifest!(_manifest, path),
    do: raise("#{path} must contain a JSON object. No writes occurred.")

  defp build_apply_plan!(root, existing_manifest, opts, allow_resolution?) do
    topology = discover_topology!(root, existing_manifest, opts)
    validate_owned_topology!(existing_manifest, topology)

    dependency =
      resolve_dependency_identity!(root, topology, existing_manifest, opts, allow_resolution?)

    package = plan_package_json!(topology, dependency, existing_manifest)
    source = read_required_sources!(topology)

    {mix_exs, restores} =
      patch_mix_exs!(
        source.mix_exs,
        topology,
        dependency,
        existing_restores(existing_manifest)
      )

    restores =
      put_restore!(restores, "mix.lockOriginalState", dependency.original_lock_state)

    {config_exs, restores} = patch_config_exs!(source.config_exs, restores)
    {dev_exs, restores} = patch_dev_exs!(source.dev_exs, topology, restores)
    {app_js, restores} = patch_app_js!(source.app_js, restores)
    {root_layout, restores} = patch_root_layout!(source.root_layout, restores)

    managed_files = managed_files(topology)
    package_keys = package.owned_keys

    manifest =
      render_manifest(%{
        topology: topology,
        dependency: dependency,
        managed_files: managed_files,
        package_keys: package_keys,
        restores: restores,
        dependency_owned: dependency.owned?,
        lock_owned: dependency.lock_owned?
      })

    plan = ProjectPatch.new!(root, recover: false)

    plan =
      plan
      |> ProjectPatch.write_file!(Path.join(root, "mix.exs"), mix_exs)
      |> maybe_write_lock(root, dependency)
      |> ProjectPatch.write_file!(Path.join(root, "config/config.exs"), config_exs)
      |> ProjectPatch.write_file!(Path.join(root, "config/dev.exs"), dev_exs)
      |> ProjectPatch.write_file!(Path.join(root, "assets/js/app.js"), app_js)
      |> ProjectPatch.write_file!(topology.root_layout, root_layout)
      |> ProjectPatch.write_file!(topology.package_json, package.content)
      |> plan_managed_file(topology.vite_config, render_vite_config(topology))
      |> plan_managed_file(topology.hooks_file, render_hooks_file())
      |> plan_managed_file(topology.registry_file, render_registry_file())
      |> ProjectPatch.write_file!(Path.join(root, @manifest_filename), manifest, manifest: true)

    %{
      plan: plan,
      mode: if(allow_resolution?, do: :apply, else: :check),
      package_root: topology.package_root_relative,
      client_mode: topology.client_mode,
      dependency: dependency.identity,
      npm_reference: dependency.npm_reference,
      changes: ProjectPatch.changes(plan)
    }
  end

  defp discover_topology!(root, existing_manifest, opts) do
    require_regular_file!(Path.join(root, "config/config.exs"), "Phoenix config")
    require_regular_file!(Path.join(root, "config/dev.exs"), "Phoenix development config")
    require_regular_file!(Path.join(root, "assets/js/app.js"), "Phoenix JavaScript entry")

    package = discover_package_root!(root, Keyword.get(opts, :package_root))
    root_layout = discover_root_layout!(root)
    detected_mode = detect_client_mode(root)
    requested_mode = Keyword.get(opts, :client_mode)

    client_mode =
      case requested_mode do
        nil ->
          detected_mode

        mode when mode in [:genes, :plain_js] and mode == detected_mode ->
          mode

        mode when mode in [:genes, :plain_js] ->
          raise "requested client mode #{client_mode_label(mode)} does not match the project topology (detected #{client_mode_label(detected_mode)}). No writes occurred. Run the Phoenix scaffold first."

        other ->
          raise "invalid LiveReact client mode #{inspect(other)} (expected genes or plain-js)"
      end

    if existing_manifest do
      expected_package = existing_manifest["packageRoot"]
      expected_mode = existing_manifest["clientMode"]

      unless expected_package == package.relative do
        raise "LiveReact package-root drift: the manifest owns #{inspect(expected_package)}, but discovery selected #{inspect(package.relative)}. No writes occurred. Use the original --package-root or remove the integration first."
      end

      unless expected_mode == client_mode_label(client_mode) do
        raise "LiveReact client-mode drift: the manifest owns #{expected_mode}, but the project now looks like #{client_mode_label(client_mode)}. No writes occurred. Remove and re-apply the integration after converging the Phoenix scaffold."
      end
    end

    %{
      root: root,
      package_root: package.absolute,
      package_root_relative: package.relative,
      package_json: Path.join(package.absolute, "package.json"),
      vite_config: Path.join(package.absolute, "vite.config.mjs"),
      hooks_file: Path.join([root, "assets", "js", "live-react-hooks.js"]),
      registry_file: Path.join([root, "assets", "react-components", "registry.generated.js"]),
      root_layout: root_layout,
      client_mode: client_mode
    }
  end

  defp discover_package_root!(root, explicit) do
    candidates =
      case explicit do
        nil ->
          [".", "assets"]
          |> Enum.filter(&File.regular?(Path.join([root, &1, "package.json"])))

        value when is_binary(value) ->
          [validate_package_root_argument!(value)]

        other ->
          raise "invalid --package-root #{inspect(other)}"
      end

    relative =
      case candidates do
        [one] ->
          one

        [] ->
          raise "could not find package.json at the project root or assets/package.json. No writes occurred. Create one package root or pass a project-relative --package-root."

        many ->
          raise "multiple npm package roots found: #{Enum.join(many, ", ")}. No writes occurred. Pass --package-root explicitly."
      end

    unless normalize_relative_root(relative) in [".", "assets"] do
      raise "unsupported npm package root #{inspect(relative)}. No writes occurred. The initial integration supports only package.json or assets/package.json."
    end

    absolute = Path.expand(relative, root)

    real =
      case physical_directory(absolute) do
        {:ok, path} ->
          path

        {:error, reason} ->
          raise "cannot resolve package root #{relative}: #{format_path_error(reason)}"
      end

    unless inside_root?(root, real) do
      raise "package root #{inspect(relative)} resolves outside the Phoenix project. No writes occurred."
    end

    require_regular_file!(Path.join(real, "package.json"), "npm package")
    %{relative: normalize_relative_root(relative), absolute: real}
  end

  defp validate_package_root_argument!(value) do
    cond do
      value == "" ->
        raise "--package-root may not be empty"

      Path.type(value) == :absolute ->
        raise "--package-root must be project-relative"

      Enum.any?(Path.split(value), &(&1 in ["..", ""])) ->
        raise "--package-root may not contain parent traversal"

      true ->
        value
    end
  end

  defp normalize_relative_root("."), do: "."
  defp normalize_relative_root(value), do: value |> Path.split() |> Path.join()

  defp inside_root?(root, path) do
    relative = Path.relative_to(path, root)

    relative == "." or
      (Path.type(relative) == :relative and not String.starts_with?(relative, ".."))
  end

  defp discover_root_layout!(root) do
    matches =
      [
        Path.join([root, "lib", "*_web", "components", "layouts", "root.html.heex"]),
        Path.join([root, "lib", "*_web", "templates", "layout", "root.html.heex"]),
        Path.join([root, "lib", "*_web", "templates", "layout", "root.html.leex"])
      ]
      |> Enum.flat_map(&Path.wildcard/1)
      |> Enum.uniq()

    case matches do
      [one] ->
        one

      [] ->
        raise "could not find one canonical Phoenix root layout. No writes occurred. Expected lib/*_web/components/layouts/root.html.heex or the legacy template path."

      many ->
        raise "multiple Phoenix root layouts found: #{Enum.map_join(many, ", ", &Path.relative_to(&1, root))}. No writes occurred."
    end
  end

  defp detect_client_mode(root) do
    genes_indicators = [
      Path.join(root, "build-client.hxml"),
      Path.join([root, "src_haxe", "client", "Boot.hx"]),
      Path.join([root, "haxe_libraries", "genes.hxml"])
    ]

    if Enum.all?(genes_indicators, &File.regular?/1), do: :genes, else: :plain_js
  end

  defp client_mode_label(:genes), do: "genes"
  defp client_mode_label(:plain_js), do: "plain-js"

  defp read_required_sources!(topology) do
    %{
      mix_exs: File.read!(Path.join(topology.root, "mix.exs")),
      config_exs: File.read!(Path.join(topology.root, "config/config.exs")),
      dev_exs: File.read!(Path.join(topology.root, "config/dev.exs")),
      app_js: File.read!(Path.join(topology.root, "assets/js/app.js")),
      root_layout: File.read!(topology.root_layout)
    }
  end

  defp existing_restores(nil), do: %{}
  defp existing_restores(manifest), do: manifest["managed"]["restores"]

  defp managed_files(topology) do
    [topology.vite_config, topology.hooks_file, topology.registry_file]
    |> Enum.map(&Path.relative_to(&1, topology.root))
    |> Enum.sort()
  end

  defp resolve_dependency_identity!(
         root,
         topology,
         existing_manifest,
         opts,
         allow_resolution?
       ) do
    dependencies = Keyword.get(opts, :mix_dependencies, [])
    declaration = Enum.find(dependencies, &(dependency_name(&1) == :live_react))
    mix_exs = File.read!(Path.join(root, "mix.exs"))
    marker_owned? = String.contains?(mix_exs, "BEGIN reflaxe_elixir live_react_dependency")
    textual_declaration? = Regex.match?(~r/\{\s*:live_react\b/, mix_exs)

    if textual_declaration? and is_nil(declaration) and not marker_owned? do
      raise "mix.exs declares :live_react, but the loaded Mix project did not expose that dependency. No writes occurred. Re-run the task in the project root after reloading Mix."
    end

    dependency_owned? =
      cond do
        existing_manifest ->
          existing_manifest["managed"]["dependencyOwned"]

        marker_owned? ->
          raise "mix.exs contains a PhoenixHx LiveReact dependency marker but #{@manifest_filename} is missing. No writes occurred. Restore the manifest or remove the stale marker manually."

        textual_declaration? ->
          false

        true ->
          true
      end

    expected_source = dependency_source!(declaration, dependency_owned?)
    lock_path = Path.join(root, "mix.lock")
    {initial_lock_content, lock_existed?} = read_lock_source(lock_path)
    initial_lock = read_lock_content!(initial_lock_content, lock_path)

    original_lock_state =
      if existing_manifest do
        restores = existing_manifest["managed"]["restores"]
        require_restore_key!(restores, "mix.lockOriginalState")
        validate_original_lock_state!(restores["mix.lockOriginalState"])
      else
        original_lock_state!(initial_lock_content, initial_lock, lock_existed?)
      end

    if dependency_owned? and is_nil(existing_manifest) and Map.has_key?(initial_lock, :live_react) do
      raise "mix.lock already contains an unowned :live_react entry while mix.exs has no matching dependency. No writes occurred. Remove the stale lock entry or declare the dependency explicitly before retrying."
    end

    checkout = dependency_checkout(root, expected_source)

    current =
      validate_resolved_dependency(
        expected_source,
        initial_lock,
        checkout,
        topology,
        opts
      )

    {resolved, lock_content, lock_changed?} =
      cond do
        match?({:ok, _}, current) ->
          {:ok, value} = current
          {value, initial_lock_content, false}

        not allow_resolution? ->
          {:error, reason} = current

          raise "LiveReact dependency drift: #{reason}. No writes occurred and --check did not access the network. Run `mix haxe.phoenix.live_react` to resolve the checked dependency."

        true ->
          resolver = Keyword.get(opts, :dependency_resolver, &resolve_with_loaded_mix!/1)

          resolution =
            resolver.(%{
              root: root,
              current_lock_content: initial_lock_content,
              dependencies: dependencies,
              dependency: declaration || default_live_react_dependency(),
              dependency_owned?: dependency_owned?,
              dependency_path: checkout
            })

          resolved_lock_content = Map.fetch!(resolution, :lock_content)
          resolved_checkout = Map.get(resolution, :dependency_path, checkout)
          resolved_lock = read_lock_content!(resolved_lock_content, "temporary LiveReact lock")

          unless Map.delete(resolved_lock, :live_react) == Map.delete(initial_lock, :live_react) do
            raise "Mix changed lock entries unrelated to :live_react while resolving the integration. No tracked files were written. Converge the existing dependencies first, then retry."
          end

          case validate_resolved_dependency(
                 expected_source,
                 resolved_lock,
                 resolved_checkout,
                 topology,
                 opts
               ) do
            {:ok, value} ->
              owned_lock =
                insert_lock_entry!(
                  initial_lock_content,
                  initial_lock,
                  Map.fetch!(resolved_lock, :live_react)
                )

              {value, owned_lock, owned_lock != initial_lock_content}

            {:error, reason} ->
              raise "Mix resolved :live_react, but its identity is not usable: #{reason}. No tracked integration files were written."
          end
      end

    if existing_manifest do
      unless existing_manifest["mixDependency"] == resolved.identity and
               existing_manifest["npmReference"] == resolved.npm_reference do
        raise "LiveReact dependency identity changed from the owned manifest. No writes occurred. Remove and re-apply the integration after reviewing the upstream change."
      end
    end

    Map.merge(resolved, %{
      owned?: dependency_owned?,
      lock_owned?:
        if(existing_manifest,
          do: existing_manifest["managed"]["lockOwned"],
          else: dependency_owned?
        ),
      lock_content: lock_content,
      lock_changed?: lock_changed?,
      original_lock_state: original_lock_state
    })
  end

  defp dependency_name({name, _}) when is_atom(name), do: name
  defp dependency_name({name, _, _}) when is_atom(name), do: name
  defp dependency_name(_), do: nil

  defp dependency_source!(nil, true) do
    %{
      kind: :git,
      repository: normalize_git_repository(@live_react_repository),
      ref: @live_react_revision
    }
  end

  defp dependency_source!(nil, false) do
    raise "the LiveReact manifest says the Mix dependency is hand-owned, but the loaded project has no :live_react dependency. No writes occurred."
  end

  defp dependency_source!({:live_react, requirement}, false) when is_binary(requirement) do
    %{kind: :hex, package: "live_react", requirement: requirement}
  end

  defp dependency_source!({:live_react, opts}, false) when is_list(opts),
    do: dependency_source_from_options!(nil, opts)

  defp dependency_source!({:live_react, requirement, opts}, false)
       when is_binary(requirement) and is_list(opts),
       do: dependency_source_from_options!(requirement, opts)

  defp dependency_source!(declaration, true) do
    # A task-owned declaration is deliberately fixed. Reloaded Mix may expose it on reruns.
    expected = dependency_source!(nil, true)

    case declaration do
      nil ->
        expected

      declaration ->
        actual = declared_dependency_source!(declaration)

        if actual == expected do
          expected
        else
          raise "the task-owned :live_react declaration changed from #{inspect(default_live_react_dependency())} to #{inspect(declaration)}. No writes occurred."
        end
    end
  end

