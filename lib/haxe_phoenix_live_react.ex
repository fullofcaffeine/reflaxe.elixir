      raise "config/dev.exs has no watchers configuration. No writes occurred. Canonical Phoenix watcher topology is required."
    end

    search_end = min(length(lines) - 1, watcher_index + 16)

    case Enum.find(watcher_index..search_end, fn index ->
           String.contains?(Enum.at(lines, index), "[")
         end) do
      nil ->
        raise "config/dev.exs watchers configuration has no recognizable list. No writes occurred."

      list_index ->
        list_index + 1
    end
  end

