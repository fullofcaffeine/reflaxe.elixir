  defp patch_live_react_dependency!(content, %{owned?: true}) do
    begin_token = "BEGIN reflaxe_elixir live_react_dependency"
    end_token = "END reflaxe_elixir live_react_dependency"
    desired = live_react_dependency_lines()

    case ProjectPatch.replace_marker_block_lines(content, begin_token, end_token, desired) do
      {:ok, updated} ->
        updated

      :error ->
        raise "mix.exs has a malformed LiveReact dependency marker. No writes occurred."

