    "%{\n" <> body <> "}\n"
  end

  defp resolve_with_loaded_mix!(context) do
    project_file = Mix.Project.project_file()

    unless is_binary(project_file) and Path.dirname(Path.expand(project_file)) == context.root do
      raise "dependency resolution must run from the target Mix project root"
    end

    temp_directory =
      Path.join(
        System.tmp_dir!(),
        "reflaxe_live_react_resolve_#{System.unique_integer([:positive, :monotonic])}"
      )

    File.mkdir!(temp_directory)
    lockfile = Path.join(temp_directory, "mix.lock")
    File.write!(lockfile, context.current_lock_content)

    dependencies =
      if Enum.any?(context.dependencies, &(dependency_name(&1) == :live_react)) do
        context.dependencies
      else
        [context.dependency | context.dependencies]
      end

    Mix.ensure_application!(:hex)

    Mix.ProjectStack.post_config(
      deps: dependencies,
      lockfile: lockfile,
      deps_path: Path.join(context.root, "deps")
    )

    try do
      Mix.Task.reenable("deps.get")
      Mix.Task.run("deps.get", ["live_react"])

      %{
        lock_content: File.read!(lockfile),
        dependency_path: context.dependency_path
      }
    rescue
      error ->
        raise "could not resolve the checked stock LiveReact dependency: #{Exception.message(error)}. No tracked integration files were written; ignored dependency downloads may remain in deps/."
    after
      Enum.each([:deps, :lockfile, :deps_path], &Mix.ProjectStack.pop_post_config/1)
      File.rm(lockfile)
      File.rmdir(temp_directory)
    end
  end

