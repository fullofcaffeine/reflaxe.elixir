                    ~r/\{\s*\}/,
                    "{\n" <>
                      Enum.join(block, "\n") <> "\n" <> leading_indent(live_socket_line) <> "}",
                    global: false
                  )

                List.replace_at(lines, live_socket, replacement) |> Enum.join("\n")
              else
                List.insert_at(lines, live_socket + 1, Enum.join(block, "\n")) |> Enum.join("\n")
              end

            {updated, put_restore!(restores, "app.hooksProperty", nil)}

          many ->
            raise "assets/js/app.js has #{length(many)} LiveSocket hooks properties near construction. No writes occurred."
        end
    end
  end

  defp expected_hooks_property_lines!(restores) do
    case Map.fetch(restores, "app.hooksProperty") do
      {:ok, nil} ->
        ["hooks: window.Hooks || {},"]

      {:ok, original} when is_binary(original) ->
        [rewrite_hooks_property_with_window!(original)]

      :error ->
        raise "#{@manifest_filename} is missing app.hooksProperty restore metadata. No writes occurred."
    end
  end

  defp find_live_socket_index!(lines) do
    lines
    |> Enum.with_index()
    |> Enum.find_value(fn {line, index} ->
      if String.contains?(line, "new LiveSocket"), do: index, else: nil
    end) ||
      raise "assets/js/app.js has no recognizable LiveSocket construction. No writes occurred."
  end

  defp rewrite_hooks_property_with_window!(line) do
    trimmed = String.trim(line)
    trailing_comma? = String.ends_with?(trimmed, ",")
    without_comma = if trailing_comma?, do: String.trim_trailing(trimmed, ","), else: trimmed

    case String.split(without_comma, "hooks:", parts: 2) do
      [_prefix, rhs] ->
        expression = String.trim(rhs)

        merged =
          cond do
            String.starts_with?(expression, "{") and String.ends_with?(expression, "}") ->
              inner =
                expression
                |> String.trim_leading("{")
                |> String.trim_trailing("}")
                |> String.trim()

              if inner == "",
                do: "{...(window.Hooks || {})}",
                else: "{" <> inner <> ", ...(window.Hooks || {})}"

            expression != "" ->
              "{...#{expression}, ...(window.Hooks || {})}"

            true ->
              raise "assets/js/app.js has an empty hooks property. No writes occurred."
          end

        "hooks: " <> merged <> if(trailing_comma?, do: ",", else: "")

      _ ->
        raise "assets/js/app.js hooks property is not recognizable. No writes occurred."
    end
  end

  defp patch_root_layout!(content, restores) do
    begin_token = "BEGIN reflaxe_elixir live_react_vite_assets"
    end_token = "END reflaxe_elixir live_react_vite_assets"
    restore_key = "layout.appScript"

    validate_marker_pairs!(content, [{begin_token, end_token}], "Phoenix root layout")

    existing_original = Map.get(restores, restore_key)

    desired =
      if is_binary(existing_original), do: root_asset_inner_lines!(existing_original), else: []

    case ProjectPatch.replace_marker_block_lines(content, begin_token, end_token, desired) do
      {:ok, updated} ->
        if is_binary(existing_original) do
          {updated, restores}
        else
          raise "#{@manifest_filename} is missing the original root-layout app script needed for recovery. No writes occurred."
        end

      :error ->
        raise "Phoenix root layout has a malformed LiveReact assets marker. No writes occurred."

      :missing ->
        if String.contains?(content, "LiveReact.Reload.vite_assets") do
          raise "Phoenix root layout already contains an unowned LiveReact Vite asset wrapper. No writes occurred. Manual integration is required."
        end

        {original, start_index, end_index, indent} = find_root_app_script!(content)
        restores = put_restore!(restores, restore_key, original)
        lines = String.split(content, "\n", trim: false)

        block =
          marker_lines(
            begin_token,
            end_token,
            root_asset_inner_lines!(original),
            indent,
            "<%!--",
            "--%>"
          )

        updated =
          lines
          |> replace_line_range(start_index, end_index, Enum.join(block, "\n"))
          |> Enum.join("\n")

        {updated, restores}
    end
  end

  defp find_root_app_script!(content) do
    lines = String.split(content, "\n", trim: false)

    starts =
      lines
      |> Enum.with_index()
      |> Enum.filter(fn {line, _index} ->
        String.contains?(line, "<script") and
          (String.contains?(line, ~s|/assets/app.js|) or
             String.contains?(line, ~s|/assets/app.js\"|))
      end)

    case starts do
      [{line, start_index}] ->
        end_index =
          if String.contains?(line, "</script>") do
            start_index
          else
            Enum.find(start_index..min(length(lines) - 1, start_index + 5), fn index ->
              String.contains?(Enum.at(lines, index), "</script>")
            end)
          end

        if is_nil(end_index) do
          raise "Phoenix root layout app script is not closed within a supported span. No writes occurred."
        end

        original = lines |> Enum.slice(start_index..end_index) |> Enum.join("\n")
        {original, start_index, end_index, leading_indent(line)}

      [] ->
        raise "Phoenix root layout has no canonical /assets/app.js script. No writes occurred. Run the Phoenix scaffold first."

      many ->
        raise "Phoenix root layout has #{length(many)} app script candidates. No writes occurred."
    end
  end

  defp root_asset_inner_lines!(original) when is_binary(original) do
    original_lines = String.split(original, "\n", trim: false)
    original_indent = leading_indent(hd(original_lines))

    script =
      Enum.map(original_lines, fn line ->
        stripped =
          if String.starts_with?(line, original_indent),
            do: String.replace_prefix(line, original_indent, ""),
            else: String.trim_leading(line)

        "  " <> stripped
      end)

    [~s|<LiveReact.Reload.vite_assets assets={["/js/app.js"]}>|] ++
      script ++ ["</LiveReact.Reload.vite_assets>"]
  end

  defp root_asset_inner_lines!(_),
    do: raise("missing original Phoenix root-layout app script")

  defp replace_line_range(lines, start_index, end_index, replacement) do
    before = Enum.take(lines, start_index)
    after_lines = Enum.drop(lines, end_index + 1)
    before ++ [replacement] ++ after_lines
  end

  defp append_marker_block(content, begin_token, end_token, desired, indent, comment_prefix) do
    block = marker_lines(begin_token, end_token, desired, indent, comment_prefix)
    String.trim_trailing(content) <> "\n\n" <> Enum.join(block, "\n") <> "\n"
  end

  defp marker_lines(begin_token, end_token, desired, indent, comment_prefix) do
    marker_lines(begin_token, end_token, desired, indent, comment_prefix, "")
  end

  defp marker_lines(begin_token, end_token, desired, indent, "<%!--", "--%>") do
    ["#{indent}<%!-- #{begin_token} --%>"] ++
      Enum.map(desired, &(indent <> &1)) ++ ["#{indent}<%!-- #{end_token} --%>"]
  end

  defp marker_lines(begin_token, end_token, desired, indent, comment_prefix, suffix) do
    ["#{indent}#{comment_prefix} #{begin_token}#{suffix}"] ++
      Enum.map(desired, &(indent <> &1)) ++
      ["#{indent}#{comment_prefix} #{end_token}#{suffix}"]
  end

  defp validate_marker_pairs!(content, pairs, label) do
    case ProjectPatch.validate_marker_pairs(content, pairs) do
      :ok ->
        :ok

      {:error, reason} ->
        raise "#{label} has malformed or overlapping ownership markers: #{inspect(reason)}. No writes occurred."
    end
  end

  defp put_restore!(restores, key, value) do
    case Map.fetch(restores, key) do
      :error ->
        Map.put(restores, key, value)

      {:ok, ^value} ->
        restores

      {:ok, existing} ->
        raise "#{@manifest_filename} restore metadata for #{key} changed from #{inspect(existing)} to #{inspect(value)}. No writes occurred."
    end
  end

  defp require_restore_key!(restores, key) do
    unless Map.has_key?(restores, key) do
      raise "#{@manifest_filename} is missing #{key} restore metadata. No writes occurred."
    end

    :ok
  end

  defp trailing_whitespace(content) do
    trimmed = String.trim_trailing(content)
    binary_part(content, byte_size(trimmed), byte_size(content) - byte_size(trimmed))
  end

  defp leading_indent(line) do
    case Regex.run(~r/^\s*/, line) do
      [indent] -> indent
      _ -> ""
    end
  end

  defp physical_directory(path) do
    case System.cmd("pwd", ["-P"], cd: path, stderr_to_stdout: true) do
      {resolved, 0} -> {:ok, String.trim(resolved)}
      {output, _status} -> {:error, {:physical_path, String.trim(output)}}
    end
  rescue
    error in File.Error -> {:error, error.reason}
  end

  defp format_path_error({:physical_path, message}), do: message
  defp format_path_error(reason), do: :file.format_error(reason)

  defp build_remove_plan!(root, manifest, opts) do
    topology = discover_topology!(root, manifest, opts)
    validate_owned_topology!(manifest, topology)
    restores = manifest["managed"]["restores"]
    source = read_required_sources!(topology)
    package = remove_package_values!(topology, manifest)
    retain_live_react? = "dependencies.live_react" in package.retained_keys

    mix_exs =
      remove_mix_wiring!(source.mix_exs, manifest, topology, restores, retain_live_react?)

    config_exs =
      remove_appended_owned_marker!(
        source.config_exs,
        "BEGIN reflaxe_elixir live_react_config",
        "END reflaxe_elixir live_react_config",
        live_react_config_lines(),
        restores["config.trailingWhitespace"],
        "config/config.exs LiveReact config"
      )

    dev_exs = remove_dev_wiring!(source.dev_exs, topology, restores)
    app_js = remove_app_js_wiring!(source.app_js, restores)
    root_layout = remove_root_layout_wiring!(source.root_layout, restores)

    plan = ProjectPatch.new!(root, recover: false)

    plan =
      plan
      |> ProjectPatch.write_file!(Path.join(root, "mix.exs"), mix_exs)
      |> maybe_remove_lock_entry(root, manifest, retain_live_react?)
      |> ProjectPatch.write_file!(Path.join(root, "config/config.exs"), config_exs)
      |> ProjectPatch.write_file!(Path.join(root, "config/dev.exs"), dev_exs)
      |> ProjectPatch.write_file!(Path.join(root, "assets/js/app.js"), app_js)
      |> ProjectPatch.write_file!(topology.root_layout, root_layout)
      |> ProjectPatch.write_file!(topology.package_json, package.content)

    plan =
      Enum.reduce(manifest["managed"]["files"], plan, fn relative, current_plan ->
        path = Path.join(root, relative)

        case File.read(path) do
          {:ok, content} ->
            case ProjectPatch.signature_status(content, @generated_signature) do
              :owned ->
                ProjectPatch.delete_file!(current_plan, path)

              :unowned ->
                raise "cannot remove #{relative}: the generated ownership signature is missing. No writes occurred. Preserve the file and remove it manually after review."

              {:error, reason} ->
                raise "cannot remove #{relative}: duplicate ownership signature #{inspect(reason)}. No writes occurred."
            end

          {:error, :enoent} ->
            current_plan

          {:error, reason} ->
            raise "cannot read #{path}: #{:file.format_error(reason)}"
        end
      end)

    plan =
      ProjectPatch.update_file!(
        plan,
        Path.join(root, @manifest_filename),
        fn
          %{state: :regular} -> :delete
          %{state: :missing} -> raise "#{@manifest_filename} disappeared during removal planning"
        end,
        manifest: true
      )

    %{
      plan: plan,
      mode: :remove,
      package_root: topology.package_root_relative,
      client_mode: topology.client_mode,
      retained_package_keys: package.retained_keys,
      retained_live_react_dependency:
        retain_live_react? and manifest["managed"]["dependencyOwned"],
      changes: ProjectPatch.changes(plan)
    }
  end

