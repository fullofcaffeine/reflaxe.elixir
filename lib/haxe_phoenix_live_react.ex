  defp desired_asset_alias_lines(_alias_name, desired_line, _original), do: [desired_line]

  defp single_line_alias?(line, alias_name) do
    Regex.match?(~r/^[\s]*[\"']#{Regex.escape(alias_name)}[\"']\s*:\s*\[.*\]\s*,?\s*$/, line)
  end

  defp render_single_line_asset_alias!(line, alias_name, desired_line) do
    indent = leading_indent(line)
    unindented = String.replace_prefix(line, indent, "")

    pattern =
      ~r/^([\"']#{Regex.escape(alias_name)}[\"']\s*:\s*)\[(.*)\](\s*,?\s*)$/

    with [_, prefix, encoded_items, suffix] <- Regex.run(pattern, unindented),
         {:ok, items} <- Code.string_to_quoted("[#{encoded_items}]") do
      unless is_list(items) and Enum.all?(items, &is_binary/1) do
        raise "mix.exs #{alias_name} single-line alias must contain literal string tasks. No writes occurred. Expand the alias manually for custom terms."
      end

      desired = desired_line |> String.trim_trailing(",") |> Code.string_to_quoted!()
      esbuild_count = Enum.count(items, &String.starts_with?(&1, "esbuild"))

      if esbuild_count > 1 do
        raise "mix.exs #{alias_name} contains multiple esbuild tasks. No writes occurred. Manual integration is required."
      end

      updated_items =
        if esbuild_count == 1,
          do: Enum.map(items, &if(String.starts_with?(&1, "esbuild"), do: desired, else: &1)),
          else: [desired | items]

      rendered_items =
        Enum.with_index(updated_items)
        |> Enum.map(fn {item, index} ->
          suffix = if index == length(updated_items) - 1, do: "", else: ","
          "  " <> inspect(item) <> suffix
        end)

      [prefix <> "["] ++ rendered_items ++ ["]" <> suffix]
    else
      _ ->
        raise "mix.exs #{alias_name} is not a supported single-line string-task alias. No writes occurred."
    end
  end

  defp find_alias_span!(lines, alias_name) do
    start_index =
      lines
      |> Enum.with_index()
      |> Enum.find_value(fn {line, index} ->
        if Regex.match?(~r/[\"']#{Regex.escape(alias_name)}[\"']\s*:\s*\[/, line),
          do: index,
          else: nil
      end)

    if is_nil(start_index) do
      raise "mix.exs has no #{inspect(alias_name)} list alias. No writes occurred. Canonical PhoenixHx aliases are required."
    end

    opening = Enum.at(lines, start_index)
    initial_depth = bracket_delta(opening)

    if initial_depth < 0 do
      raise "mix.exs #{alias_name} is not a recognizable list alias. No writes occurred."
    end

    if initial_depth == 0,
      do: {start_index, start_index},
      else: find_alias_end!(lines, alias_name, start_index, initial_depth)
  end

  defp find_alias_end!(lines, alias_name, start_index, initial_depth) do
    {end_index, _depth} =
      Enum.reduce_while((start_index + 1)..(length(lines) - 1), {nil, initial_depth}, fn index,
                                                                                         {_end,
                                                                                          depth} ->
        next_depth = depth + bracket_delta(Enum.at(lines, index))

        if next_depth == 0,
          do: {:halt, {index, next_depth}},
          else: {:cont, {nil, next_depth}}
      end)

    if is_nil(end_index) do
      raise "mix.exs #{alias_name} list is not balanced. No writes occurred."
    end

    {start_index, end_index}
  end

  defp bracket_delta(line) do
    line
    |> String.graphemes()
    |> Enum.reduce(0, fn
      "[", depth -> depth + 1
      "]", depth -> depth - 1
      _character, depth -> depth
    end)
  end

  defp find_unowned_vite_task(lines, start_index, end_index) do
    Enum.any?(start_index..end_index, fn index ->
      line = Enum.at(lines, index)
      String.contains?(line, "npm run assets:build") or String.contains?(line, "npm install")
    end)
  end

  defp alias_insertion_index(lines, start_index, end_index) do
    marker_end =
      (start_index + 1)..(end_index - 1)
      |> Enum.find(fn index ->
        String.contains?(Enum.at(lines, index), "END reflaxe_elixir haxe_compile_client_alias")
