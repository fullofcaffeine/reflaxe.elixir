  end

  defp insert_lock_entry!(content, lock, entry) when is_map(lock) do
    if Map.has_key?(lock, :live_react) do
      raise "cannot insert an owned :live_react lock entry over an existing entry. No writes occurred."
    end

    updated =
      if map_size(lock) == 0 do
        render_lock(%{live_react: entry})
      else
        lines = String.split(content, "\n", trim: false)
        closing_index = canonical_lock_closing_index!(lines)
        insert_index = lock_entry_insertion_index!(lines, closing_index, "live_react")

        List.insert_at(lines, insert_index, lock_entry_line(:live_react, entry))
        |> Enum.join("\n")
      end

    expected = Map.put(lock, :live_react, entry)

    unless read_lock_content!(updated, "planned LiveReact lock") == expected do
      raise "could not preserve mix.lock while inserting the LiveReact entry. No writes occurred."
    end

    updated
  end

  defp canonical_lock_closing_index!(lines) do
    index =
      lines
      |> Enum.with_index()
      |> Enum.reverse()
      |> Enum.find_value(fn {line, index} -> if String.trim(line) == "", do: nil, else: index end)

    if is_integer(index) and String.trim(Enum.at(lines, index)) == "}" do
      index
    else
      raise "mix.lock is not in the canonical multiline map shape. No writes occurred. Run `mix deps.get` to normalize it before enabling LiveReact."
    end
  end

  defp lock_entry_insertion_index!(lines, closing_index, name) do
    entries =
      lines
      |> Enum.take(closing_index)
      |> Enum.with_index()
      |> Enum.flat_map(fn {line, index} ->
        case Regex.run(~r/^\s*"([^"]+)":\s+/, line) do
          [_, entry_name] -> [{entry_name, index}]
          _ -> []
        end
      end)

    if entries == [] do
      raise "mix.lock contains dependencies but not canonical one-entry-per-line lock entries. No writes occurred. Run `mix deps.get` to normalize it before enabling LiveReact."
    end

    Enum.find_value(entries, closing_index, fn {entry_name, index} ->
      if entry_name > name, do: index, else: nil
    end)
  end

  defp lock_entry_line(name, entry),
    do: "  \"#{name}\": #{inspect(entry, limit: :infinity)},"

  defp sha256(content),
    do: :crypto.hash(:sha256, content) |> Base.encode16(case: :lower)

  defp read_lock_content!(content, label) do
    directory = Path.join(System.tmp_dir!(), "reflaxe_live_react_lock_read")
    File.mkdir_p!(directory)
    path = Path.join(directory, "#{System.unique_integer([:positive, :monotonic])}.lock")
    File.write!(path, content, [:write, :exclusive])

    try do
      Mix.Dep.Lock.read(path)
    after
      File.rm(path)
    end
  rescue
    error -> raise "cannot parse #{label}: #{Exception.message(error)}"
  end

