  defp validate_resolved_dependency(source, lock, checkout, topology, opts) do
    with :ok <- validate_checkout_directory(checkout),
         {:ok, identity} <- identity_from_lock(source, lock, checkout, topology.root),
         :ok <- validate_checkout_identity(identity, checkout, opts),
         {:ok, npm_reference} <- npm_reference(topology, checkout) do
      {:ok,
       %{
         identity: identity,
         npm_reference: npm_reference,
         checkout: checkout,
         source: source
       }}
    end
  end

  defp validate_checkout_directory(checkout) do
    cond do
      not File.dir?(checkout) ->
        {:error, "dependency checkout is missing at #{checkout}"}

      not File.regular?(Path.join(checkout, "package.json")) ->
        {:error, "#{checkout} is missing stock LiveReact package.json"}

      not File.regular?(Path.join(checkout, "mix.exs")) ->
        {:error, "#{checkout} is missing stock LiveReact mix.exs"}

      true ->
        :ok
    end
  end

  defp identity_from_lock(%{kind: :git} = source, lock, _checkout, _root) do
    case lock[:live_react] do
      {:git, repository, revision, _opts} when is_binary(repository) and is_binary(revision) ->
        normalized = normalize_git_repository(repository)

        cond do
          normalized != source.repository ->
            {:error,
             "Mix lock repository #{inspect(normalized)} does not match #{inspect(source.repository)}"}

          not Regex.match?(~r/^[0-9a-f]{40}$/i, revision) ->
            {:error, "Mix lock revision is not a full Git commit"}

          is_binary(source.ref) and Regex.match?(~r/^[0-9a-f]{40}$/i, source.ref) and
              String.downcase(source.ref) != String.downcase(revision) ->
            {:error, "Mix lock revision does not match the declared Git ref"}

          true ->
            {:ok,
             %{
               "name" => "live_react",
               "sourceKind" => "git",
               "repository" => normalized,
               "resolvedRevision" => String.downcase(revision)
             }}
        end

      nil ->
        {:error, "mix.lock has no :live_react entry"}

      other ->
        {:error, "mix.lock contains #{inspect(other)} instead of a Git LiveReact lock"}
    end
  end

  defp identity_from_lock(%{kind: :hex} = source, lock, _checkout, _root) do
    case lock[:live_react] do
      {:hex, package, version, checksum, _managers, _deps, repository, outer_checksum}
      when is_binary(version) and is_binary(checksum) ->
        package = to_string(package)

        cond do
          package != source.package ->
            {:error, "Hex package #{package} does not match #{source.package}"}

          not Version.match?(version, source.requirement) ->
            {:error, "Hex version #{version} does not satisfy #{source.requirement}"}

          true ->
            {:ok,
             %{
               "name" => "live_react",
               "sourceKind" => "hex",
               "package" => package,
               "repository" => to_string(repository),
               "resolvedVersion" => version,
               "checksum" => normalize_lock_checksum(checksum),
               "outerChecksum" => normalize_lock_checksum(outer_checksum)
             }}
        end

      nil ->
        {:error, "mix.lock has no :live_react entry"}

      other ->
        {:error, "mix.lock contains #{inspect(other)} instead of a Hex LiveReact lock"}
    end
  rescue
    error in Version.InvalidRequirementError -> {:error, Exception.message(error)}
  end

  defp identity_from_lock(%{kind: :path, path: declared}, _lock, checkout, root) do
    expanded = Path.expand(declared, root)

    cond do
      Path.type(declared) == :absolute ->
        {:error, "path dependencies must be project-relative"}

      not inside_root?(root, expanded) ->
        {:error, "path dependency escapes the Phoenix project"}

      Path.expand(checkout) != expanded ->
        {:error, "resolved checkout does not match the declared path dependency"}

      true ->
        package = Jason.decode!(File.read!(Path.join(checkout, "package.json")))
        version = package["version"]

        if is_binary(version) do
          {:ok,
           %{
             "name" => "live_react",
             "sourceKind" => "path",
             "path" => Path.relative_to(expanded, root),
             "packageVersion" => version
           }}
        else
          {:error, "path dependency package.json has no string version"}
        end
    end
  end

  defp validate_checkout_identity(
         %{"sourceKind" => "git", "resolvedRevision" => revision},
         checkout,
         opts
       ) do
    revision_reader = Keyword.get(opts, :git_revision, &git_revision!/1)

    if String.downcase(revision_reader.(checkout)) == revision do
      :ok
    else
      {:error, "dependency checkout HEAD does not match mix.lock"}
    end
  rescue
    error -> {:error, "cannot verify dependency checkout: #{Exception.message(error)}"}
  end

  defp validate_checkout_identity(_identity, _checkout, _opts), do: :ok

  defp git_revision!(checkout) do
    case System.cmd("git", ["-C", checkout, "rev-parse", "HEAD"], stderr_to_stdout: true) do
      {revision, 0} -> String.trim(revision)
      {output, _} -> raise "git rev-parse failed: #{String.trim(output)}"
    end
  end

  defp npm_reference(topology, checkout) do
    case physical_directory(Path.expand(checkout)) do
      {:ok, absolute_checkout} ->
        build_npm_reference(topology, absolute_checkout)

      {:error, reason} ->
        {:error, "cannot resolve npm LiveReact checkout: #{format_path_error(reason)}"}
    end
  end

  defp build_npm_reference(topology, absolute_checkout) do
    checkout_from_root = Path.relative_to(absolute_checkout, topology.root)

    cond do
      not inside_root?(topology.root, absolute_checkout) ->
        {:error, "npm LiveReact checkout escapes the Phoenix project"}

      Path.type(checkout_from_root) != :relative ->
        {:error, "npm LiveReact path is not project-relative"}

      checkout_from_root == "." ->
        {:error, "npm LiveReact checkout cannot be the package root"}

      true ->
        prefix = if topology.package_root_relative == ".", do: "", else: "../"
        {:ok, "file:" <> prefix <> checkout_from_root}
    end
  end

  defp normalize_git_repository(repository) do
    repository
    |> String.trim()
    |> String.replace(~r/^git:\/\//, "https://")
    |> String.replace(~r/^git@github\.com:/, "https://github.com/")
    |> String.trim_trailing("/")
    |> String.replace(~r/\.git$/, "")
  end

  defp normalize_lock_checksum(nil), do: nil

  defp normalize_lock_checksum(checksum) when is_binary(checksum) do
    if Regex.match?(~r/^[0-9a-f]+$/i, checksum) and rem(byte_size(checksum), 2) == 0 do
      String.downcase(checksum)
    else
      Base.encode16(checksum, case: :lower)
    end
  end

  defp read_lock_source(path) do
    case File.read(path) do
      {:ok, content} -> {content, true}
      {:error, :enoent} -> {"%{}\n", false}
      {:error, reason} -> raise "cannot read #{path}: #{:file.format_error(reason)}"
    end
  end

