        updated = lines |> List.insert_at(insert_at, Enum.join(block, "\n")) |> Enum.join("\n")
        {updated, put_restore!(restores, "dev.esbuildWatcher", nil)}

      many ->
        raise "config/dev.exs contains #{length(many)} esbuild watcher entries. No writes occurred. Manual integration is required."
    end
  end

  defp balanced_single_line_expression?(line) do
    occurrence_count(line, "{") == occurrence_count(line, "}") and
      occurrence_count(line, "[") == occurrence_count(line, "]") and
      occurrence_count(line, "(") == occurrence_count(line, ")")
  end

  defp occurrence_count(content, token), do: length(:binary.matches(content, token))

