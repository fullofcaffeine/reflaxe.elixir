  defp remove_package_values!(topology, manifest) do
    value = Jason.decode!(File.read!(topology.package_json))
    owned = MapSet.new(manifest["managed"]["packageKeys"])
    hand_usage = hand_owned_browser_packages(topology)

    {updated, retained} =
      Enum.reduce(@managed_package_values, {value, []}, fn {path, raw_expected}, {json, kept} ->
        dotted = Enum.join(path, ".")

        if MapSet.member?(owned, dotted) do
          expected =
            if raw_expected == :npm_live_react_reference,
              do: manifest["npmReference"],
              else: raw_expected

          case fetch_json_path(json, path) do
            {:ok, ^expected} ->
              package = List.last(path)

              if MapSet.member?(hand_usage, package) do
                {json, [dotted | kept]}
              else
                {delete_json_path(json, path), kept}
              end

            :missing ->
              {json, kept}

            {:ok, actual} ->
              raise "cannot remove package.json #{dotted}: owned value drifted to #{inspect(actual)}. No writes occurred."
          end
        else
          {json, kept}
        end
      end)

    %{content: Jason.encode!(updated, pretty: true) <> "\n", retained_keys: Enum.sort(retained)}
  end

  defp hand_owned_browser_packages(topology) do
    managed = MapSet.new([topology.vite_config, topology.hooks_file, topology.registry_file])

    files =
      [
        Path.join(topology.root, "assets/**/*.{js,jsx,ts,tsx,mjs,cjs}"),
        Path.join(topology.package_root, "*.{js,jsx,ts,tsx,mjs,cjs}")
      ]
      |> Enum.flat_map(&Path.wildcard/1)
      |> Enum.reject(&(MapSet.member?(managed, &1) or String.contains?(&1, "/node_modules/")))

    Enum.reduce(files, MapSet.new(), fn path, packages ->
      source = File.read!(path)

      packages
      |> maybe_mark_package(source, "live_react")
      |> maybe_mark_package(source, "react")
      |> maybe_mark_package(source, "react-dom")
      |> maybe_mark_package(source, "vite")
      |> maybe_mark_package(source, "@vitejs/plugin-react")
    end)
  end

  defp maybe_mark_package(packages, source, package) do
    if Regex.match?(
         ~r/(?:from\s+|import\s*\(?\s*)[\"']#{Regex.escape(package)}(?:[\/'\"])/,
         source
       ),
       do: MapSet.put(packages, package),
       else: packages
  end

  defp maybe_remove_lock_entry(plan, _root, _manifest, true), do: plan

  defp maybe_remove_lock_entry(plan, root, manifest, false) do
    if manifest["managed"]["lockOwned"] do
      path = Path.join(root, "mix.lock")
      restores = manifest["managed"]["restores"]
      require_restore_key!(restores, "mix.lockOriginalState")
      original_state = validate_original_lock_state!(restores["mix.lockOriginalState"])
      current_content = File.read!(path)
      current_lock = read_lock_content!(current_content, path)

      unless Map.has_key?(current_lock, :live_react) do
        raise "the task-owned :live_react lock entry is missing. No writes occurred. Restore the lock entry or retain LiveReact as hand-owned before retrying."
      end

      retained_lock = Map.delete(current_lock, :live_react)
      retained_content = remove_lock_entry_line!(current_content, :live_react)

      cond do
        retained_lock == %{} and original_state["kind"] == "missing" ->
          ProjectPatch.delete_file!(plan, path)

        retained_lock == %{} and original_state["kind"] == "empty" ->
          ProjectPatch.write_file!(plan, path, original_state["content"])

        true ->
          ProjectPatch.write_file!(plan, path, retained_content)
      end
    else
      plan
    end
  end

  defp remove_lock_entry_line!(content, name) when is_atom(name) do
    lines = String.split(content, "\n", trim: false)
    pattern = ~r/^\s*"#{Regex.escape(Atom.to_string(name))}":\s+.*,$/

    indices =
      lines
      |> Enum.with_index()
      |> Enum.flat_map(fn {line, index} ->
        if Regex.match?(pattern, line), do: [index], else: []
      end)

    case indices do
      [index] ->
        List.delete_at(lines, index) |> Enum.join("\n")

      _ ->
        raise "mix.lock must contain exactly one canonical #{name} entry line. No writes occurred."
    end
  end

  defp remove_appended_owned_marker!(
         content,
         begin_token,
         end_token,
         expected,
         trailing,
         label
       )
       when is_binary(trailing) do
    lines = String.split(content, "\n", trim: false)
    {begin_index, end_index} = marker_indices!(lines, begin_token, end_token, label)
    prefix = Enum.take(lines, begin_index)
    suffix = Enum.drop(lines, end_index + 1)

    unless List.last(prefix) == "" do
      raise "#{label} lost its owned separator line. No writes occurred."
    end

    _validated = restore_owned_marker!(content, begin_token, end_token, expected, nil, label)

    base = prefix |> Enum.drop(-1) |> Enum.join("\n") |> Kernel.<>(trailing)

    if Enum.all?(suffix, &(String.trim(&1) == "")) do
      base
    else
      base <> "\n" <> Enum.join(suffix, "\n")
    end
  end

  defp remove_appended_owned_marker!(
         _content,
         _begin_token,
         _end_token,
         _expected,
         _trailing,
         label
       ) do
    raise "#{@manifest_filename} is missing trailing-whitespace restore metadata for #{label}. No writes occurred."
  end

  defp unwrap_owned_marker!(content, begin_token, end_token, expected, label) do
    lines = String.split(content, "\n", trim: false)
    {begin_index, end_index} = marker_indices!(lines, begin_token, end_token, label)
    marker_indent = leading_indent(Enum.at(lines, begin_index))
    inner = Enum.slice(lines, (begin_index + 1)..(end_index - 1))
    actual = Enum.map(inner, &strip_expected_indent(&1, marker_indent))

    unless actual == expected do
      raise "#{label} content drifted inside its ownership markers. No writes occurred."
    end

    replace_line_range_with_lines(lines, begin_index, end_index, inner) |> Enum.join("\n")
  end

  defp remove_inserted_dependency_marker!(
         content,
         begin_token,
         end_token,
         expected,
         label
       ) do
    block =
      marker_lines(begin_token, end_token, expected, "      ", "#")
      |> Enum.join("\n")

    inserted = "\n" <> block <> "\n"

    case :binary.matches(content, inserted) do
      [{position, length}] ->
        binary_part(content, 0, position) <>
          binary_part(content, position + length, byte_size(content) - position - length)

      _ ->
        raise "#{label} no longer matches the exact inserted dependency block. No writes occurred. Restore the owned block or retain the dependency as hand-owned before retrying."
    end
  end

  defp restore_owned_marker!(content, begin_token, end_token, expected, original, label) do
    lines = String.split(content, "\n", trim: false)
    {begin_index, end_index} = marker_indices!(lines, begin_token, end_token, label)
    marker_indent = leading_indent(Enum.at(lines, begin_index))

    actual =
      lines
      |> Enum.slice((begin_index + 1)..(end_index - 1))
      |> Enum.map(&strip_expected_indent(&1, marker_indent))

    unless actual == expected do
      raise "#{label} content drifted inside its ownership markers. No writes occurred."
    end

    replacement =
      case original do
        nil -> []
        value when is_binary(value) -> String.split(value, "\n", trim: false)
      end

    replace_line_range_with_lines(lines, begin_index, end_index, replacement) |> Enum.join("\n")
  end

  defp strip_expected_indent(line, ""), do: line

  defp strip_expected_indent(line, indent) do
    if String.starts_with?(line, indent), do: String.replace_prefix(line, indent, ""), else: line
  end

  defp marker_inner_lines!(content, begin_token, end_token, label) do
    lines = String.split(content, "\n", trim: false)
    {begin_index, end_index} = marker_indices!(lines, begin_token, end_token, label)

    lines
    |> Enum.slice((begin_index + 1)..(end_index - 1))
    |> Enum.map(&String.trim_leading/1)
  end

  defp marker_indices!(lines, begin_token, end_token, label) do
    begins = matching_indices(lines, begin_token)
    ends = matching_indices(lines, end_token)

    case {begins, ends} do
      {[first], [last]} when first < last -> {first, last}
      _ -> raise "#{label} must contain exactly one ordered marker pair. No writes occurred."
    end
  end

  defp marker_presence(content, begin_token, end_token) do
    lines = String.split(content, "\n", trim: false)

    case {matching_indices(lines, begin_token), matching_indices(lines, end_token)} do
      {[], []} -> :missing
      {[_], [_]} -> :present
      _ -> raise "malformed ownership markers for #{begin_token}. No writes occurred."
    end
  end

  defp matching_indices(lines, token) do
    lines
    |> Enum.with_index()
    |> Enum.filter(fn {line, _index} ->
      Regex.match?(~r/(?:^|\s)#{Regex.escape(token)}(?=$|\s)/, line)
    end)
    |> Enum.map(&elem(&1, 1))
  end

  defp replace_line_range_with_lines(lines, start_index, end_index, replacements) do
    Enum.take(lines, start_index) ++ replacements ++ Enum.drop(lines, end_index + 1)
  end
end
