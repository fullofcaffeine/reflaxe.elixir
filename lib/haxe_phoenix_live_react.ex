  end

  defp insert_into_function_list!(content, function_pattern, block_lines, label) do
    case Regex.run(function_pattern, content, return: :index) do
      [{function_position, _length} | _] ->
        remainder = String.slice(content, function_position..-1//1)

        case :binary.match(remainder, "[") do
          {list_position, _} ->
            insertion = function_position + list_position + 1

            String.slice(content, 0, insertion) <>
              "\n" <>
              Enum.join(block_lines, "\n") <>
              "\n" <>
              String.slice(content, insertion..-1//1)

          :nomatch ->
            raise "could not find the list in #{label}. No writes occurred."
        end

      _ ->
        raise "could not find #{label}. No writes occurred."
    end
  end

