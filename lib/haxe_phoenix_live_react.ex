      path = opts[:path] ->
        %{kind: :path, path: to_string(path)}

      requirement ->
        %{kind: :hex, package: to_string(opts[:hex] || :live_react), requirement: requirement}

      true ->
        raise "unsupported :live_react dependency options #{inspect(opts)}. No writes occurred."
    end
